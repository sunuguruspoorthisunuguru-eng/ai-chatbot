# ---------------- SIDEBAR ----------------

with st.sidebar:
    st.title("⚙️ Settings")

    st.write("**AI Model**")
    st.code(MODEL)

    st.caption("Responses are generated by your local Ollama model.")

    if st.button("🗑️ Clear conversation", use_container_width=True):
        st.session_state.messages = []
        st.rerun()

    st.divider()
    st.caption("Nova AI • Built with Python and Streamlit")

# ---------------- SESSION STATE ----------------

if "messages" not in st.session_state:
    st.session_state.messages = []

# ---------------- WELCOME SCREEN ----------------

if not st.session_state.messages:
    st.markdown("### 👋 Welcome! What can I help you with?")

    st.markdown(
        "Ask questions, learn programming, explore AI, "
        "or get help with your college projects."
    )

    col1, col2, col3 = st.columns(3)

    with col1:
        if st.button("🐍 Learn Python", use_container_width=True):
            st.session_state.pending_prompt = (
                "Teach me Python programming with simple examples."
            )
            st.rerun()

    with col2:
        if st.button("🧠 Explore AI", use_container_width=True):
            st.session_state.pending_prompt = (
                "Explain artificial intelligence in simple words."
            )
            st.rerun()

    with col3:
        if st.button("💡 Project ideas", use_container_width=True):
            st.session_state.pending_prompt = (
                "Suggest five useful AI projects for a college student."
            )
            st.rerun()

# ---------------- DISPLAY CHAT HISTORY ----------------

for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])

# ---------------- CHAT INPUT ----------------

prompt = st.chat_input("Message Nova AI...")

if "pending_prompt" in st.session_state:
    prompt = st.session_state.pop("pending_prompt")

# ---------------- AI RESPONSE ----------------

if prompt:
    st.session_state.messages.append({
        "role": "user",
        "content": prompt
    })

    with st.chat_message("user"):
        st.markdown(prompt)

    with st.chat_message("assistant"):
        placeholder = st.empty()

        try:
            payload = {
                "model": MODEL,
                "messages": [
                    {
                        "role": "system",
                        "content": (
                            "You are Nova, a helpful AI assistant. "
                            "Give accurate, friendly answers. "
                            "Explain technical concepts simply."
                        )
                    },
                    *st.session_state.messages
                ],
                "stream": True
            }

            with requests.post(
                OLLAMA_URL,
                json=payload,
                stream=True,
                timeout=(10, 600)
            ) as response:

                response.raise_for_status()
                answer = ""

                for line in response.iter_lines():
                    if not line:
                        continue

                    data = json.loads(line)

                    if data.get("message", {}).get("content"):
                        answer += data["message"]["content"]
                        placeholder.markdown(answer + "▌")

                    if data.get("done"):
                        break

            if not answer:
                answer = "The model returned an empty response."

            placeholder.markdown(answer)

            st.session_state.messages.append({
                "role": "assistant",
                "content": answer
            })

        except requests.exceptions.ConnectionError:
            error = (
                "Cannot connect to Ollama. Open a terminal and run "
                "`ollama serve`, if Ollama is not already running."
            )
            placeholder.error(error)

        except requests.exceptions.Timeout:
            placeholder.error(
                "The AI took too long to respond. Try a shorter prompt "
                "or a smaller model."
            )

        except requests.exceptions.HTTPError as e:
            if e.response is not None and e.response.status_code == 404:
                placeholder.error(
                    f"Model '{MODEL}' was not found. Run "
                    f"`ollama pull {MODEL}` in your terminal."
                )
            else:
                placeholder.error(f"Ollama HTTP error: {e}")

        except Exception as e:
            placeholder.error(f"Something went wrong: {e}")

